#!/usr/bin/env node
// Builds Kladde's build-time plugins into the app (docs/PLUGINS.md).
//
//   npm run plugins                      install, check and wire up the plugins of kladde.plugins.json
//   npm run plugins -- --file <path>     another plugin list (also: KLADDE_PLUGINS_FILE)
//   npm run plugins -- --skip-install    the packages are installed already (e.g. by your own npm install)
//   npm run plugins -- --check           only check the version matrix, change nothing
//   npm run plugins -- --reset           back to a build without plugins
//
// kladde.plugins.json pins every plugin package:
//   { "plugins": { "@team/kladde-plugin-time": "1.4.0", "kladde-plugin-hello": "file:examples/kladde-plugin-hello" } }
//
// Checks (any failure stops with exit code 1, before anything is built):
//   - package name kladde-plugin-*, kladde.id, exports "./server" and/or "./client"
//   - peerDependencies["@kladde/plugin-api"] contains this Kladde's plugin API version
//   - peerDependencies.react (client plugins) contains the bundled React version
//   - kladde.app (optional) contains this Kladde's version; the pinned version is the installed one
//   - no two plugins share an id
// Then it writes:
//   packages/server/plugins/<id>.js (+ .d.ts)   the server part bundled with its dependencies (esbuild)
//   packages/server/src/plugins/installed.ts    the list the server loads
//   packages/client/src/plugins/installed.ts    the list the client bundles (Vite imports the packages)
//   packages/client/src/plugins/tailwind-content.json   the plugins' files, so Tailwind sees their classes
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { checkPluginPackage, checkPluginSet, PLUGIN_PACKAGE_PATTERN, parseVersion } from '../packages/plugin-api/src/compat.ts';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const at = (...p) => path.join(root, ...p);
const args = process.argv.slice(2);
const flag = (name) => args.includes(`--${name}`);
const option = (name) => {
  const i = args.indexOf(`--${name}`);
  return i >= 0 ? args[i + 1] : undefined;
};

const SERVER_BUNDLES = at('packages', 'server', 'plugins');
const SERVER_LIST = at('packages', 'server', 'src', 'plugins', 'installed.ts');
const CLIENT_LIST = at('packages', 'client', 'src', 'plugins', 'installed.ts');
const TAILWIND_LIST = at('packages', 'client', 'src', 'plugins', 'tailwind-content.json');
const HEADER = '// Generated by scripts/plugins.mjs from kladde.plugins.json – do not edit by hand.\n// Without plugins (the default build) the list is empty; `npm run plugins -- --reset` restores this file.\n';

const fail = (lines) => {
  console.error(`\n✖ Plugins cannot be built into Kladde:\n${[].concat(lines).map((l) => `  - ${l}`).join('\n')}\n`);
  process.exit(1);
};
const readJson = (file) => JSON.parse(fs.readFileSync(file, 'utf8'));
const write = (file, text) => {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== text) fs.writeFileSync(file, text);
};
const quote = (s) => `'${String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;

/** Empties packages/server/plugins (it always exists, the Docker image copies it) */
function resetBundles() {
  fs.rmSync(SERVER_BUNDLES, { recursive: true, force: true });
  fs.mkdirSync(SERVER_BUNDLES, { recursive: true });
  fs.writeFileSync(path.join(SERVER_BUNDLES, 'README.md'), '# Generated\n\nServer bundles of the build-time plugins (`npm run plugins`). Not in git.\n');
}

function writeLists(plugins) {
  const meta = (p) => `name: ${quote(p.name)}, version: ${quote(p.version)}, api: ${quote(p.api)}, id: ${quote(p.id)}, defaultEnabled: ${p.defaultEnabled}`;
  const server = plugins.filter((p) => p.server);
  write(
    SERVER_LIST,
    `${HEADER}import type { InstalledServerPlugin } from './types.js';\n${server.map((p, i) => `import plugin${i} from '../../plugins/${p.id}.js';\n`).join('')}\nexport const installedPlugins: InstalledServerPlugin[] = [${server.length ? `\n${server.map((p, i) => `  { ${meta(p)}, plugin: plugin${i} },\n`).join('')}` : ''}];\n`
  );
  const client = plugins.filter((p) => p.client);
  write(
    CLIENT_LIST,
    `${HEADER}import type { InstalledClientPlugin } from './types';\n${client.map((p, i) => `import plugin${i} from '${p.name}/client';\n`).join('')}\nexport const installedPlugins: InstalledClientPlugin[] = [${client.length ? `\n${client.map((p, i) => `  { ${meta(p)}, plugin: plugin${i} },\n`).join('')}` : ''}];\n`
  );
  write(TAILWIND_LIST, `${JSON.stringify(client.map((p) => p.tailwind), null, 2)}\n`);
}

/** The file an export condition points to ("./server": "./dist/server.js" or { import, default, … }) */
function exportTarget(exports, key) {
  let target = exports?.[key];
  while (target && typeof target === 'object') target = target.import ?? target.node ?? target.default;
  return typeof target === 'string' ? target : null;
}

// ------------------------------------------------------------------ main

const listFile = path.resolve(root, option('file') ?? process.env.KLADDE_PLUGINS_FILE ?? 'kladde.plugins.json');
if (flag('reset') || !fs.existsSync(listFile)) {
  if (!flag('check')) {
    resetBundles();
    writeLists([]);
  }
  console.log(flag('reset') ? '✔ Back to a build without plugins.' : `No plugin list (${path.relative(root, listFile)}): building without plugins.`);
  process.exit(0);
}

let pinned;
try {
  pinned = readJson(listFile).plugins ?? {};
} catch (err) {
  fail(`${path.relative(root, listFile)} is no valid JSON: ${err.message}`);
}
if (typeof pinned !== 'object' || Array.isArray(pinned)) fail('"plugins" must be an object { "<package>": "<version or spec>" }');
const entries = Object.entries(pinned);
const badNames = entries.filter(([name, spec]) => !PLUGIN_PACKAGE_PATTERN.test(name) || typeof spec !== 'string' || !spec.trim());
if (badNames.length) fail(badNames.map(([name]) => `"${name}": plugin packages are named kladde-plugin-<name> and pinned to a version or spec`));
// Relative file: specs are relative to the plugin list, wherever npm runs
const specOf = (spec) => (spec.startsWith('file:') ? `file:${path.relative(root, path.resolve(path.dirname(listFile), spec.slice(5))) || '.'}` : spec);

if (entries.length && !flag('check') && !flag('skip-install')) {
  const specs = entries.map(([name, spec]) => `${name}@${specOf(spec)}`);
  // --legacy-peer-deps: a plugin for another plugin API is reported below with the matrix, not as npm's ERESOLVE
  console.log(`Installing ${specs.join(', ')} …`);
  try {
    execFileSync(process.platform === 'win32' ? 'npm.cmd' : 'npm', ['install', '--no-save', '--no-audit', '--no-fund', '--legacy-peer-deps', ...specs], { cwd: root, stdio: 'inherit' });
  } catch {
    fail('npm install of the plugins failed (see above); a private registry needs its .npmrc');
  }
}

const host = {
  api: readJson(at('packages', 'plugin-api', 'package.json')).version,
  app: readJson(at('package.json')).version,
  react: readJson(at('node_modules', 'react', 'package.json')).version,
};

const problems = [];
const plugins = [];
for (const [name, spec] of entries) {
  const dir = at('node_modules', ...name.split('/'));
  if (!fs.existsSync(path.join(dir, 'package.json'))) {
    problems.push(`${name} is not installed (run without --skip-install / --check, or install it yourself)`);
    continue;
  }
  const real = fs.realpathSync(dir);
  const pkg = readJson(path.join(real, 'package.json'));
  const checked = checkPluginPackage(pkg, host, parseVersion(spec) ? spec : undefined);
  problems.push(...checked.problems);
  if (!checked.plugin) continue;
  const serverEntry = checked.plugin.server ? exportTarget(pkg.exports, './server') : null;
  const clientEntry = checked.plugin.client ? exportTarget(pkg.exports, './client') : null;
  for (const [kind, entry] of [['server', serverEntry], ['client', clientEntry]]) {
    if (checked.plugin[kind] && (!entry || !fs.existsSync(path.join(real, entry)))) problems.push(`${name}: "exports./${kind}" points to ${entry ?? 'nothing'}, which does not exist (is the package built?)`);
  }
  plugins.push({
    ...checked.plugin,
    defaultEnabled: pkg.kladde?.defaultEnabled === true,
    serverFile: serverEntry && path.join(real, serverEntry),
    tailwind: clientEntry ? `${path.relative(at('packages', 'client'), path.dirname(path.join(real, clientEntry))).split(path.sep).join('/')}/**/*.{js,mjs,jsx,ts,tsx}` : null,
  });
}
problems.push(...checkPluginSet(plugins));
if (problems.length) fail(problems);

console.log(`\nKladde ${host.app} · @kladde/plugin-api ${host.api} · React ${host.react}`);
for (const p of plugins) console.log(`  ✔ ${p.id.padEnd(20)} ${p.name}@${p.version}  (plugin API ${p.api}${p.server ? ', server' : ''}${p.client ? ', client' : ''})`);
if (!plugins.length) console.log('  (no plugins)');
if (flag('check')) {
  console.log('\n✔ The version matrix fits.');
  process.exit(0);
}

// The server part runs from packages/server/plugins/<id>.js: bundled with its own dependencies, so the runtime
// image needs no plugin packages; express and the plugin API come from the host
const esbuild = await import('esbuild');
resetBundles();
for (const p of plugins.filter((x) => x.server)) {
  await esbuild.build({
    entryPoints: [p.serverFile],
    outfile: path.join(SERVER_BUNDLES, `${p.id}.js`),
    bundle: true,
    platform: 'node',
    format: 'esm',
    target: 'node22',
    external: ['express', '@kladde/plugin-api', '@kladde/plugin-api/*'],
    // CommonJS dependencies inside the ES module bundle still find `require`
    banner: { js: "import { createRequire as __kladdeRequire } from 'node:module'; const require = __kladdeRequire(import.meta.url);" },
    legalComments: 'none',
    logLevel: 'warning',
  });
  fs.writeFileSync(path.join(SERVER_BUNDLES, `${p.id}.d.ts`), "import type { ServerPlugin } from '@kladde/plugin-api/server';\ndeclare const plugin: ServerPlugin;\nexport default plugin;\n");
}
writeLists(plugins);
console.log(`\n✔ ${plugins.length} plugin(s) wired up. Next: npm run build`);
