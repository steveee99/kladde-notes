const dict: Record<Lang, Record<I18nKey, string>> = { de, en };

export function tl(lang: Lang, key: I18nKey, vars?: Record<string, string | number>): string {
  let str = dict[lang]?.[key] ?? dict.de[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      str = str.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
    }
  }
  return str;
}

export function t(key: I18nKey, vars?: Record<string, string | number>): string {
  return tl(current, key, vars);
}

/** Localizes known top-level PARA / Zettelkasten folder names while keeping underlying disk/sync paths intact */
export function folderDisplayName(folderPath: string, lang: Lang = current): string {
  if (!folderPath) return tl(lang, 'common.topLevel');
  const map: Record<string, I18nKey> = {
    [PARA.inbox]: 'para.folderInbox',
    [PARA.projects]: 'para.folderProjects',
    [PARA.areas]: 'para.folderAreas',
    [PARA.resources]: 'para.folderResources',
    [PARA.archive]: 'para.folderArchive',
    [PARA.zettel]: 'para.folderZettel',
  };
  return folderPath
    .split('/')
    .map((seg) => (map[seg] ? tl(lang, map[seg]) : seg))
    .join('/');
}

export function folderLeafDisplayName(folderPath: string, lang: Lang = current): string {
  const leaf = folderPath.split('/').pop() ?? '';
  if (!leaf) return tl(lang, 'common.topLevelPlain');
  return folderDisplayName(leaf, lang);
}

export function zettelTypeLabel(id: ZettelType, lang: Lang = current): { label: string; hint: string } {
  if (id === 'flüchtig') return { label: tl(lang, 'para.zettelFleeting'), hint: tl(lang, 'para.zettelFleetingHint') };
  if (id === 'literatur') return { label: tl(lang, 'para.zettelLiterature'), hint: tl(lang, 'para.zettelLiteratureHint') };
  return { label: tl(lang, 'para.zettelPermanent'), hint: tl(lang, 'para.zettelPermanentHint') };
}

