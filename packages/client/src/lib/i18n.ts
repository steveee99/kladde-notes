export type Lang = 'de' | 'en';

const KEY = 'kladde_lang';
const listeners = new Set<() => void>();

function loadLang(): Lang {
  try {
    const raw = typeof localStorage !== 'undefined' ? localStorage.getItem(KEY) : null;
    if (raw === 'en' || raw === 'de') return raw;
  } catch {
    // ignore storage errors
  }
  return 'de';
}

let current: Lang = loadLang();

function applyLang(lang: Lang): void {
  if (typeof document !== 'undefined') {
    document.documentElement.lang = lang;
  }
}
applyLang(current);

if (typeof window !== 'undefined') {
  window.addEventListener('storage', (e) => {
    if (e.key === KEY) {
      const next = loadLang();
      if (next !== current) {
        current = next;
        applyLang(current);
        listeners.forEach((l) => l());
      }
    }
  });
}

export function getLang(): Lang {
  return current;
}

export function setLang(lang: Lang): void {
  const next: Lang = lang === 'en' ? 'en' : 'de';
  if (current === next) return;
  current = next;
  try {
    if (typeof localStorage !== 'undefined') localStorage.setItem(KEY, next);
  } catch {
    // ignore private mode / quota errors
  }
  applyLang(next);
  listeners.forEach((l) => l());
}

function subscribe(l: () => void) {
  listeners.add(l);
  return () => listeners.delete(l);
}

export function useLang(): Lang {
  return useSyncExternalStore(subscribe, () => current);
}

export function locale(lang: Lang = current): string {
  return lang === 'en' ? 'en-US' : 'de-DE';
}

